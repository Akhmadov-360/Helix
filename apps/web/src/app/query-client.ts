import { QueryClient } from "@tanstack/react-query";

// Без глобального staleTime кэш всегда «протухший» → ensureQueryData/mount дёргает сеть заново
// на каждом переходе между страницами (напр. /v1/auth/me, вызываемый из loader'а почти каждого
// роута), даже если данные не менялись секунду назад — лишняя нагрузка на БД без выгоды.
// 15s — базовая свежесть для совместно редактируемых данных (доска, задачи, контакты): не мешает
// увидеть свои же изменения (они пишутся в кэш напрямую мутациями, staleTime их не касается),
// и достаточно коротко, чтобы чужое изменение не «зависло» надолго.
//
// refetchOnWindowFocus: false — раньше было true "как бесплатный сигнал что что-то изменилось",
// на живом демо это оказалось **шумом**: каждое переключение на вкладку (в DevTools, Upstash,
// Resend, документацию) триггерило волну refetch'ей ВСЕХ активных queries — сотни запросов за
// 2-3 минуты разбора одного сценария. staleTime=15s уже покрывает свежесть на реальных взаимодействиях
// (клик по кнопке, ввод в поле); фокус вкладки — плохой прокси для "пользователь хочет свежие данные".
// Modern SaaS-конвенция (Linear/Notion/Vercel) тоже это выключает.
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 15_000,
      refetchOnWindowFocus: false,
    },
  },
});
