import { QueryClient } from "@tanstack/react-query";

// Без глобального staleTime кэш всегда «протухший» → ensureQueryData/mount дёргает сеть заново
// на каждом переходе между страницами (напр. /v1/auth/me, вызываемый из loader'а почти каждого
// роута), даже если данные не менялись секунду назад — лишняя нагрузка на БД без выгоды.
// 15s — базовая свежесть для совместно редактируемых данных (доска, задачи, контакты): не мешает
// увидеть свои же изменения (они пишутся в кэш напрямую мутациями, staleTime их не касается),
// и достаточно коротко, чтобы чужое изменение не «зависло» надолго. refetchOnWindowFocus — намеренно
// НЕ выключаем (в отличие от типового дефолта): без WebSocket-пуша это единственный бесплатный
// сигнал «возможно, что-то изменилось, стоит перепроверить» при возврате на вкладку.
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 15_000,
      refetchOnWindowFocus: true,
    },
  },
});
